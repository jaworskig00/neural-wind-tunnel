"""Exact solver pressure distributions for the app's presets, for side-by-side comparison.

The app can show what the reference solver says for the same section and incidence, drawn behind the
surrogate's curve. That is the honest way to present an approximation: not a claim about its error,
but the two curves on one axis.

Only the presets are covered, swept across the trained incidence range. Running the panel method in
the browser would mean porting it, and a free-form section has no reference to compare against
anyway -- the overlay appears when the design is a stock one and quietly does not when it is not.

    uv run python -m tools.dataset.make_overlay
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from tools.solver.geometry import cst
from tools.solver.solve import solve

OUTPUT = Path("public/models/solver_overlay.json")
ALPHA_STEP = 0.5
ALPHA_RANGE = (-6.0, 10.0)

#: Fitted CST weights of the presets, read from the fixture the browser also uses, so the overlay
#: cannot drift from the geometry the app actually draws.
FIXTURE = Path("src/geometry/__fixtures__/cst.json")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    fixture = json.loads(FIXTURE.read_text())
    alphas = np.arange(ALPHA_RANGE[0], ALPHA_RANGE[1] + 1e-9, ALPHA_STEP)

    cases = {}
    for case in fixture["cases"]:
        upper = np.asarray(case["upperWeights"], dtype=np.float64)
        lower = np.asarray(case["lowerWeights"], dtype=np.float64)
        airfoil = cst(upper, lower, panel_count=320)

        entries = []
        for alpha in alphas:
            result = solve(airfoil, float(alpha))
            entries.append(
                {
                    "alphaDeg": round(float(alpha), 3),
                    "status": result.status.value,
                    "cl": round(float(result.cl), 6),
                    "cd": None if np.isnan(result.cd) else round(float(result.cd), 7),
                    "cmQuarter": round(float(result.cm_quarter), 6),
                    "cp": [round(float(value), 4) for value in result.cp_stations],
                }
            )
        cases[case["name"]] = entries
        converged = sum(entry["status"] == "ok" for entry in entries)
        print(f"  {case['name']}: {len(entries)} angles, {converged} converged")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(
            {
                "note": "Exact panel-method results for the app's presets, drawn behind the "
                "surrogate's prediction. Generated by tools/make_overlay.py.",
                "alphaStep": ALPHA_STEP,
                "alphaRange": list(ALPHA_RANGE),
                "cases": cases,
            },
            separators=(",", ":"),
        ),
        encoding="utf-8",
    )
    print(f"wrote {args.output} ({args.output.stat().st_size / 1e6:.2f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
